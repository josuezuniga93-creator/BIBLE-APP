const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const base = process.env.REVIEW_URL || 'http://127.0.0.1:3120';
(async () => {
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({viewport:{width:390,height:844}});
    page.setDefaultTimeout(30000);
    page.setDefaultNavigationTimeout(90000);
    const errors=[];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/api/bible/chapter?**', route => route.fulfill({json:{verses:Array.from({length:20},(_,i)=>({verse:i+1,text:'A passage for checking selection and reading layout.'}))}}));
    await page.goto(base+'/lexicon?book=43&chapter=3');
    await page.locator('#verse-1').click();
    await page.locator('#verse-2').click();
    await page.getByRole('button',{name:'Highlight blue',exact:true}).click();
    assert.equal(await page.locator('.marked-blue').count(),2);
    await page.getByRole('button',{name:'Remove highlight',exact:true}).click();
    assert.equal(await page.locator('.marked-blue').count(),0);
    await page.getByRole('button',{name:'Search Scripture',exact:true}).click();
    await page.getByRole('textbox',{name:'Passage reference'}).fill('Jhon 3: 14-18');
    await page.getByRole('button',{name:'Open passage',exact:true}).click();
    await page.waitForURL('**select=*');
    assert.equal(await page.locator('.verse').count(),5);
    await page.goto(base+'/dictionary');
    await page.getByPlaceholder('Search the dictionary').fill('justificaton');
    assert.equal(await page.locator('.dictionary-entry').count(),1);
    assert.match(await page.locator('.dictionary-entry').innerText(),/Justification/);
    await page.locator('.dictionary-entry summary').click();
    await page.screenshot({path:'/tmp/bible-dictionary-final.png'});
    await page.goto(base+'/library/imitation-of-christ?chapter=2');
    await page.getByRole('button',{name:'Table of contents',exact:true}).click();
    assert.ok(await page.locator('.reader-contents nav button').count()>2);
    await page.locator('.reader-contents nav button').nth(3).click();
    await page.waitForFunction(()=>document.querySelector('.chapter-controls')?.textContent.includes('Page 5 of'));
    await page.locator('[data-reader-word]').first().waitFor();
    const word=page.locator('[data-reader-word]').nth(8);
    await word.hover(); await page.mouse.down(); await page.waitForTimeout(650); await page.mouse.up();
    await page.getByRole('button',{name:'Blue',exact:true}).click();
    assert.equal(await page.locator('[data-hl-id]').count(),1);
    await page.reload();
    await page.locator('[data-hl-id]').waitFor();
    assert.equal(await page.locator('[data-hl-id]').count(),1);
    await page.waitForTimeout(300);
    await page.screenshot({path:'/tmp/bible-reader-final.png'});
    await page.goto(base+'/learn?doc=westminster-confession');
    await page.getByRole('button',{name:/Read now|Continue reading/i}).first().click();
    await page.getByRole('button',{name:'Table of contents',exact:true}).click();
    const total=await page.locator('.reader-contents nav button').count();
    assert.ok(total>1);
    await page.locator('.reader-contents nav button').nth(1).click();
    console.log('Historical reader:',await page.locator('.chapter-controls').innerText());
    await page.goto(base);
    await page.waitForTimeout(1500);
    const badge = page.getByRole('button', {name:'Keep Going',exact:true});
    if (await badge.isVisible()) await badge.click();
    await page.locator('.memory-preview').scrollIntoViewIfNeeded();
    await page.screenshot({path:'/tmp/bible-home-final.png'});
    const dimensions=await page.locator('.featured-resources .media-photo').evaluateAll(nodes=>nodes.map(node=>({w:node.clientWidth,h:node.clientHeight,filter:getComputedStyle(node).filter})));
    assert.ok(dimensions.every(d=>Math.abs(d.w-d.h)<2&&d.filter==='none'));
    await page.evaluate(()=>{localStorage.setItem('ryc-theme','gold-navy');document.cookie='ryc-theme=gold-navy; path=/';});
    await page.reload();
    await page.getByRole('button',{name:'Read Missionary Story',exact:true}).click();
    await page.waitForURL('**/church-history/**');
    await page.screenshot({path:'/tmp/bible-mission-final.png'});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    assert.deepEqual(errors,[]);
    console.log('PASS: multi-highlight, typo search, dictionary, both reader indexes, highlights, square featured cards, mobile layout');
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
